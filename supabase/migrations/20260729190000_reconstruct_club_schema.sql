set search_path = ''
as $$
  with events as (
    select 'training_log'::text as event_type, count(*)::bigint * 10 as event_xp
    from public.training_logs where user_id = p_user
    union all
    select 'attendance_present'::text, count(*)::bigint * 20
    from public.attendance_logs where student_id = p_user
    union all
    select 'quest_completed'::text, coalesce(sum(q.xp_reward), 0)::bigint
    from public.user_quests uq
    join public.quests q on q.id = uq.quest_id
    where uq.user_id = p_user and uq.status = 'completed'
  )
  select sum(event_xp) over ()::bigint, event_type, event_xp from events;
$$;

create or replace function public.current_streak_days(p_user uuid)
returns integer
language sql
stable
security invoker
set search_path = ''
as $$
  with activity_days as (
    select distinct created_at::date as day
    from public.training_logs where user_id = p_user
    union
    select distinct checked_at::date
    from public.attendance_logs where student_id = p_user
  ),
  ranked as (
    select day, day - row_number() over (order by day)::integer as grp
    from activity_days
    where day <= current_date
  )
  select coalesce(max(streak), 0)::integer
  from (
    select count(*) as streak
    from ranked
    group by grp
    having max(day) >= current_date - 1
  ) s;
$$;

