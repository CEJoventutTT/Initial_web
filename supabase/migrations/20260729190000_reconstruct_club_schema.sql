create or replace function public.check_in_attendance(
  p_session_id bigint,
  p_key text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  target_session public.attendance_sessions%rowtype;
  inserted_id bigint;
begin
  if current_user_id is null then
    return jsonb_build_object('ok', false, 'error', 'unauthorized');
  end if;

  select * into target_session
  from public.attendance_sessions
  where id = p_session_id;

  if not found then
    return jsonb_build_object('ok', false, 'error', 'session_not_found');
  end if;
  if not target_session.active then
    return jsonb_build_object('ok', false, 'error', 'session_inactive');
  end if;
  if target_session.expires_at is not null and now() > target_session.expires_at then
    return jsonb_build_object('ok', false, 'error', 'session_expired');
  end if;
  if now() < target_session.start_at then
    return jsonb_build_object('ok', false, 'error', 'session_not_started');
  end if;
  if target_session.end_at is not null and now() > target_session.end_at then
    return jsonb_build_object('ok', false, 'error', 'session_closed');
  end if;
  if p_key is null or p_key <> target_session.qr_key then
    return jsonb_build_object('ok', false, 'error', 'invalid_key');
  end if;
  if not exists (
    select 1 from public.enrollments
    where user_id = current_user_id
      and program_id = target_session.program_id
      and status = 'active'
  ) then
    return jsonb_build_object('ok', false, 'error', 'not_enrolled');
  end if;

  insert into public.attendance_logs (student_id, session_id, program_id)
  values (current_user_id, target_session.id, target_session.program_id)
  on conflict (student_id, session_id) do nothing
  returning id into inserted_id;

  return jsonb_build_object(
    'ok', true,
    'status', 'present',
    'xp', 20,
    'duplicate', inserted_id is null
  );
end;
$$;

